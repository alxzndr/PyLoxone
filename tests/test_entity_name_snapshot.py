@pytest.mark.parametrize("language", ["en", "de", "cs"])
def test_override_reason_translations_match_ha_core_layout(language):
    """HA core resolves enum sensor states via
    ``component.{platform}.entity.{domain}.{translation_key}.state.{state}``
    (homeassistant/helpers/translation.py).  The shipped files must
    therefore nest under ``entity.sensor.<translation_key>`` — a nested
    ``entity.sensor.loxone.<translation_key>`` would never be found.
    """
    path = REPO_ROOT / "custom_components" / DOMAIN / "translations" / f"{language}.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    flat = recursive_flatten("component.loxone.entity.", data["entity"])

    key = f"component.loxone.entity.sensor.override_reason.state.{OVERRIDE_STATE_SLUG}"
    assert key in flat, f"{language}.json does not carry {key!r}"

    if language == "en":
        # hand-read from the shipped en translation (a literal, not a
        # computed value): this key must render in the UI.
        assert flat[key] == OVERRIDE_STATE_EN

    # the old, unreachable layout must be gone
    stale_key = f"component.loxone.entity.sensor.loxone.override_reason.state.{OVERRIDE_STATE_SLUG}"
    assert stale_key not in flat, f"{language}.json still carries the dead {stale_key!r} path"

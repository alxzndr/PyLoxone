"""WP-5.1: ``has_entity_name`` adoption and the entity-name snapshot.

Acceptance criteria (docs/review/2026-09-remediation-plan.md, WP-5.1):

  * the setup creates primary entities with an *empty* name attribute (the
    device name is the display name — no more "Living Room Light Living
    Room Light") and sub-entities with *short* names ("Override Reason",
    "Total");
  * a snapshot of the entity registry (domain, entity_id, unique_id, stored name,
    device name/model linkage) after a fixture setup matches
    ``tests/snapshots/entity_names.json`` — the diff of this file between
    the pre- and post-WP-5.1 runs is reviewed in the PR;
  * no "Device Device" duplication in the snapshot: no entity's stored
    name equals the name of its own device;
  * every loxone entry carries ``has_entity_name = True``;
  * the enum sensor's translation key resolves via the HA core file
    layout ``component.loxone.entity.sensor.override_reason.state.<slug>``.

The snapshot file is generated by re-running this test with
``LOXONE_ENTITY_SNAPSHOT_OUT=/path/to/out.json pytest -q tests/test_entity_name_snapshot.py``
and then reviewed by hand (every name is read from
``tests/fixtures/LoxAPP3.json`` or the Miniserver fixture identity).
"""


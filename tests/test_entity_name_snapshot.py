async def _setup_entry(hass, mock_entry) -> None:
    mock_entry.add_to_hass(hass)
    ok = await hass.config_entries.async_setup(mock_entry.entry_id)
    await hass.async_block_till_done()
    assert ok, "entry setup failed"
    assert mock_entry.state is ConfigEntryState.LOADED


def _collect_registry_rows(hass, entry_id: str) -> list[dict]:
    """One row per loxone entity in the registry, stable order."""
    entity_registry = er.async_get(hass)
    device_registry = dr.async_get(hass)
    rows = []
    for entry in entity_registry.entities.values():
        if entry.config_entry_id != entry_id:
            continue
        device = device_registry.async_get(entry.device_id) if entry.device_id else None
        rows.append(
            {
                "domain": entry.domain,
                "entity_id": entry.entity_id,
                "unique_id": entry.unique_id,
                # the name the registry stored (None = "use the device name")
                "name": entry.name,
                "original_name": entry.original_name,
                "has_entity_name": getattr(entry, "has_entity_name", None),
                "disabled": bool(entry.disabled),
                # NOTE: entry.device_id is a random per-run uuid and must
                # not be snapshotted (the device *name*/model are stable).
                "device_name": device.name if device else None,
                "device_model": device.model if device else None,
            }
        )
    rows.sort(key=lambda row: (row["domain"], row["entity_id"]))
    return rows


# --------------------------------------------------------------------------- #
# Snapshot (compare against the committed, hand-reviewed file; regenerate
# with LOXONE_ENTITY_SNAPSHOT_OUT for the PR review diff).
# --------------------------------------------------------------------------- #
def _write_snapshot(path: str, rows: list[dict]) -> None:
    """Blocking snapshot write; only called from the regeneration path."""
    with open(path, "w", encoding="utf-8") as f:
        f.write(json.dumps(rows, indent=2) + "\n")


async def test_entity_registry_snapshot(hass, mock_connection, mock_entry, enable_custom_integrations):
    await _setup_entry(hass, mock_entry)
    rows = _collect_registry_rows(hass, mock_entry.entry_id)
    assert rows, "no loxone entities were registered"

    out_path = os.environ.get("LOXONE_ENTITY_SNAPSHOT_OUT")
    if out_path:
        # ASYNC230/240: the blocking write lives in a plain (sync) helper.
        _write_snapshot(out_path, rows)
        pytest.skip(f"snapshot regenerated at {out_path}")

    expected = json.loads(SNAPSHOT_PATH.read_text(encoding="utf-8"))
    missing = [row["entity_id"] for row in expected if row not in rows]
    extra = [row["entity_id"] for row in rows if row not in expected]
    assert not missing, f"entities missing from the runtime registry: {missing}"
    assert not extra, f"unexpected entities in the runtime registry: {extra}"


# --------------------------------------------------------------------------- #
# Acceptance: no "Device Device" duplicates in the snapshot
# --------------------------------------------------------------------------- #
def _is_device_device_duplicated(row: dict) -> bool:
    """True when the UI duplicates the device name for this entity.

    The frontend shows the device name as the device label *and* the
    entity's own name on the entity row.  For ``has_entity_name``
    entities an *empty* entity name means "use the device name" and renders
    exactly once — that is correct.  Duplicating happens when the entity
    row carries a name that either equals the device name (pre-WP-5.1
    primaries; any sub-entity whose short name repeats the parent) or
    starts with it (the old ``"<device> <suffix>"`` construction built
    from the full control name on a device already named after it).
    """
    device = row["device_name"]
    if device is None:
        return False
    if row["has_entity_name"]:
        own = row["name"]  # None = "use the device name" (fine)
    else:
        own = row["name"] if row["name"] is not None else row["original_name"]
    if own is None or own == device:
        # "own == device" is only a problem when has_entity_name is off
        # (the UI then shows device name AND entity name side by side); with
        # has_entity_name and an *explicitly stored* (user-set) name equal
        # to the device name the same duplication renders.
        return not bool(row["has_entity_name"]) or row["name"] is not None
    return own.startswith(device) or device.startswith(own)


async def test_no_duplicate_device_device_names(hass, mock_connection, mock_entry, enable_custom_integrations):
    """No "Device Device" duplicates in the snapshot.

    Pre-WP-5.1: every primary entity stored the control's full name as
    ``original_name`` and the device registry stored the very same name —
    the UI rendered "Living Room Light Switch Living Room Light Switch".
    With ``has_entity_name`` adopted the device name is the display name
    of primaries and sub-entities carry short names, so nothing may
    repeat its device name.
    """
    await _setup_entry(hass, mock_entry)
    rows = _collect_registry_rows(hass, mock_entry.entry_id)
    duplicated = [row["entity_id"] for row in rows if _is_device_device_duplicated(row)]
    assert not duplicated, f"entities duplicating their device name: {duplicated}"



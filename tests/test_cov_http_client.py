@pytest.mark.parametrize(
    ("overrides", "message"),
    [
        ({"url": ""}, "URL cannot be empty"),
        ({"username": ""}, "Username cannot be empty"),
        ({"password": ""}, "Password cannot be empty"),
        ({"scheme": "ftp"}, "Invalid scheme 'ftp'. Must be 'http' or 'https'"),
        ({"verify_ssl": "yes"}, "verify_ssl must be a boolean"),
    ],
)
def test_init_validates_its_arguments(overrides, message) -> None:
    """Bad construction arguments fail loudly at __init__ time."""
    args = {"url": "ms.local:8080", "username": "admin", "password": "secret", "session": _FakeSession()}
    args.update(overrides)

    with pytest.raises(ValueError) as excinfo:
        LoxoneAsyncHttpClient(**args)

    assert str(excinfo.value) == message


def test_init_rejects_an_already_closed_session() -> None:
    """A dead borrowed session cannot be adopted."""
    session = _FakeSession()
    session.closed = True

    with pytest.raises(ValueError) as excinfo:
        _client(session)

    assert str(excinfo.value) == "Provided session is already closed"


def test_basic_auth_header_is_utf8() -> None:
    """Credentials are encoded UTF-8, not latin-1 (JoDehli/PyLoxone#506)."""
    # Hand-derived with the stdlib, independently of the module under test.
    expected = "Basic " + base64.b64encode("admin:pässwörd".encode()).decode("ascii")
    latin1 = "Basic " + base64.b64encode("admin:pässwörd".encode("latin-1")).decode("ascii")
    # Literal, not computed by the code under test.
    assert expected == "Basic YWRtaW46cMOkc3N3w7ZyZA=="
    assert expected != latin1

    assert _basic_auth_header("admin", "pässwörd") == expected


def test_basic_auth_header_fallback_without_aiohttp_helper(monkeypatch) -> None:
    """On aiohttp < 3.12 the header is built by hand -- with the same result."""
    monkeypatch.delattr(aiohttp, "encode_basic_auth", raising=False)

    assert _basic_auth_header("admin", "pässwörd") == "Basic YWRtaW46cMOkc3N3w7ZyZA=="
